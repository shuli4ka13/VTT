import { describe, it, expect } from 'vitest';
import { counted, plural } from './plural.ts';

describe('склонение числительных', () => {
  it.each([[1, 'блок'], [2, 'блока'], [5, 'блоков'], [11, 'блоков'], [14, 'блоков'], [21, 'блок'], [22, 'блока'], [111, 'блоков'], [0, 'блоков']])(
    '%i → %s', (n, word) => { expect(plural(n, 'блок', 'блока', 'блоков')).toBe(word); },
  );

  it('число и слово вместе', () => {
    expect(counted(21, 'блок', 'блока', 'блоков')).toBe('21 блок');
  });
});
